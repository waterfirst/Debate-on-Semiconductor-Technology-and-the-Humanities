let changed = 0;
const remaining = new Map();
for (const file of files) {
  const source = fs.readFileSync(file, "utf8");
  let updated = source;
  for (const [pattern, replacement] of replacements) {
    updated = updated.replace(pattern, replacement);
  }
  if (updated !== source) {
    fs.writeFileSync(file, updated, "utf8");
    changed += 1;
  }
  for (const token of updated.match(/[가-힣]+다\./g) ?? []) {
    if (token.endsWith("니다.")) continue;
    remaining.set(token, (remaining.get(token) ?? 0) + 1);
  }
}

const report = [...remaining.entries()]
  .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], "ko"))
  .map(([token, count]) => `${token}\t${count}`)
  .join("\n");
const reportPath = path.join(book, "tmp", "remaining-tone.txt");
fs.mkdirSync(path.dirname(reportPath), { recursive: true });
fs.writeFileSync(reportPath, report, "utf8");
console.log(`formalized files: ${changed}; remaining endings: ${remaining.size}`);
